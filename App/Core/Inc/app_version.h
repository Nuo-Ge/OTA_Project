#ifndef __APP_VERSION_H__
#define __APP_VERSION_H__

#define APP_VERSION_MAJOR   1
#define APP_VERSION_MINOR   0
#define APP_VERSION_PATCH   0

#define APP_VERSION_U32     ((APP_VERSION_MAJOR << 16) | \
                             (APP_VERSION_MINOR << 8)  | \
                             (APP_VERSION_PATCH))

#endif /* __APP_VERSION_H__ */